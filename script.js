const galleryGrid = document.getElementById("galleryGrid");

artworks.forEach((artwork) => {
  const card = document.createElement("article");


function openArtwork(artwork) {
  const viewer = document.getElementById("artworkViewer");

  document.getElementById("viewerImage").src = artwork.image;
  document.getElementById("viewerTitle").textContent = artwork.title;
  document.getElementById("viewerArtist").textContent = artwork.artist;
  document.getElementById("viewerNumber").textContent = `ARTWORK No. ${artwork.id}`;
  document.getElementById("viewerYear").textContent = artwork.year;
  document.getElementById("viewerMedium").textContent = artwork.medium;
  document.getElementById("viewerMaterials").textContent = artwork.materials;

  viewer.classList.add("active");
  viewer.setAttribute("aria-hidden", "false");
}

function closeArtwork() {
  const viewer = document.getElementById("artworkViewer");

  viewer.classList.remove("active");
  viewer.setAttribute("aria-hidden", "true");
}

const viewerBack = document.getElementById("viewerBack");

viewerBack.addEventListener("click", closeArtwork);

  card.className = "artwork-card";

  card.innerHTML = `
    <div class="artwork-image-wrap">
      <img
        class="artwork-image"
        src="${artwork.image}"
        alt="${artwork.title} — ${artwork.artist}"
        loading="lazy"
      />
    </div>

    <div class="artwork-info">
      <span class="artwork-number">${artwork.id}</span>
      <h3>${artwork.title}</h3>
      <p>${artwork.artist}</p>
    </div>
  `;

  card.addEventListener("click", () => {
  openArtwork(artwork);
});

galleryGrid.appendChild(card);
});
